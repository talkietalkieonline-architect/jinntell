def presets_text() -> str:
    out = ["# Готовые заготовки отраслей (бизнес включает модули сам в личном кабинете)"]
    for ind in ip.INDUSTRIES.values():
        out.append(f"\n## {ind['label']}\n{ind.get('desc', '')}")
        for m in ind["modules"].values():
            out.append(f"— {m['label']}: {m.get('desc', '')}")
    return "\n".join(out)



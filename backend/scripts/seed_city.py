async def main():
    async with async_session() as db:
        added, skipped = 0, 0
        for a in AGENTS:
            ex = await db.execute(select(Agent).where(Agent.jinntell_link == a["jinntell_link"]))
            if ex.scalar_one_or_none():
                skipped += 1
                continue
            db.add(Agent(**a))
            added += 1
        await db.commit()
        tot = (await db.execute(select(Agent).where(Agent.visibility == "public"))).scalars().all()
        print(f"added={added} skipped={skipped} public_total={len(tot)}")


asyncio.run(main())
